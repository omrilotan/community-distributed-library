import { z } from "zod";
import { Tag, traits, type LibraryType } from "@cdl/contracts";
import { failed, tool, type Tool } from "./tool.ts";

/**
 * The whole catalogue: an assistant checking for a book already listed must
 * see the member's own copies and the books they have read, which the site's
 * browsing hides on purpose.
 */
export function searchPath({
	query,
	withinMetres,
	offset,
	tags,
}: {
	query: string;
	withinMetres?: number | undefined;
	offset?: number | undefined;
	tags?: Tag[] | undefined;
}): string {
	const narrowed = tags?.length
		? `&tags=${encodeURIComponent(tags.join(","))}`
		: "";
	return `/v1/search?q=${encodeURIComponent(query)}${withinMetres ? `&within=${withinMetres}` : ""}&offset=${offset ?? 0}${narrowed}&showMine=1&showRead=1`;
}

const tagParam = (tags: Tag[] | undefined) =>
	tags?.length ? `&tags=${encodeURIComponent(tags.join(","))}` : "";

/**
 * A member's tools, generated by hand for now from the same routes the web
 * app uses. Nothing here can do what the member's token cannot: core
 * enforces scopes, this just shapes the calls.
 *
 * Deliberately absent: marking handoffs (a physical act), and anything
 * returning another member's exact address or email. What the library lends
 * decides some tools: a library of things adds things by name, count and
 * details, and has no ISBNs to look up.
 */
export function memberTools(type: LibraryType): Tool[] {
	const kind = traits(type);
	const noun = kind.isbn ? "book" : "thing";
	// The same tool, described in the library's own words.
	const say = (books: string, things: string) => (kind.isbn ? books : things);

	return [
		tool(
			"my_profile",
			"Who I am in the library: name, area, community, role.",
			{},
			(_, { call }) => call("/v1/me"),
		),

		tool(
			"search_catalogue",
			say(
				"Search the whole catalogue by title or author, optionally narrowed by tags: every book, including ones the member owns or has marked as read (the site's own browsing leaves those out; each copy says whether it is theirs). Returns one entry per book, each listing every copy in the community with its owner, area and distance, nearest first, plus the work id for get_work. Use nextOffset to page. Search here before adding a book, to spot one already listed.",
				"Search the whole library by name, brand or model, optionally narrowed by categories: every thing, including the member's own (the site's own browsing leaves those out; each item says whether it is theirs). Returns one entry per thing with its owner, distance, whether it can be requested, how many of a set are free, and the owner's details about it. Check here before add_copy.",
			),
			{
				query: z.string().min(1).max(120),
				withinMetres: z.number().int().positive().max(20_000).optional(),
				offset: z.number().int().nonnegative().optional(),
				tags: z
					.array(Tag)
					.optional()
					.describe(
						"Tag slugs to filter by, as namespace:value. Call list_tags for the vocabulary; it is curated, so only slugs it returns work. Several tags in one namespace mean either; across namespaces they narrow.",
					),
			},
			({ query, withinMetres, offset, tags }, { call }) =>
				call(searchPath({ query, withinMetres, offset, tags })),
		),

		tool(
			"browse_shelves",
			say(
				"What is on the shelves near me right now, one entry per book with all of its copies and their owners. Filter by tags, page with offset (the reply carries nextOffset).",
				"What is in the library near me right now, one entry per thing with its owner, how many of a set are free, and the owner's details. Filter by categories, page with offset (the reply carries nextOffset).",
			),
			{
				offset: z.number().int().nonnegative().optional(),
				tags: z
					.array(Tag)
					.optional()
					.describe("Tag slugs from list_tags, as namespace:value."),
			},
			({ offset, tags }, { call }) =>
				call(`/v1/browse?offset=${offset ?? 0}${tagParam(tags)}`),
		),

		tool(
			"list_tags",
			say(
				"The library's tag vocabulary: labels, their values, and how many books carry each. Tags are curated, not free text — to use a tag that is not here, suggest it with propose_tag.",
				"The library's categories: their labels in English and Hebrew, and how many things carry each. Categories are curated, not free text — to use one that is not here, suggest it with propose_tag.",
			),
			{},
			(_, { call }) => call("/v1/tags"),
		),

		tool(
			"set_item_tags",
			kind.isbn
				? "Replace the tags on a book. Tags describe the book, so they are shared by every copy of it; I may set them on any book I own a copy of. Send the whole set, not a change."
				: "Replace the categories on one of my things. Send the whole set, not a change.",
			{ workId: z.string(), tags: z.array(Tag) },
			({ workId, tags }, { call }) =>
				call(`/v1/works/${encodeURIComponent(workId)}/tags`, {
					method: "PUT",
					body: { tags },
				}),
		),

		tool(
			"propose_tag",
			say(
				"Suggest a tag the vocabulary does not have: a value inside an existing label, or a whole new label. A moderator reviews it before anyone can use it, so nothing is applied straight away. Give workId to have it put on that book once approved.",
				"Suggest a category the library does not have. A moderator reviews it before anyone can use it, so nothing is applied straight away. Give workId to have it put on that thing once approved.",
			),
			{
				namespace: z
					.string()
					.optional()
					.describe("An existing label id from list_tags, e.g. genre."),
				namespaceLabel: z
					.string()
					.optional()
					.describe(
						"Name for a new label, when none of the existing ones fit.",
					),
				label: z
					.string()
					.min(1)
					.max(40)
					.describe("The value, in my own words."),
				workId: z.string().optional(),
			},
			({ namespace, namespaceLabel, label, workId }, { call }) =>
				call("/v1/tags/proposals", {
					method: "POST",
					body: {
						...(namespace ? { namespace } : {}),
						...(namespaceLabel ? { namespaceLabel } : {}),
						label,
						...(workId ? { workId } : {}),
					},
				}),
		),

		tool(
			"my_tag_proposals",
			"Tag suggestions I have made and what the moderators did with them.",
			{},
			(_, { call }) => call("/v1/me/tag-proposals"),
		),

		tool(
			"invite_neighbour",
			"Create a link that lets one neighbour join the library. The link comes back once and is not stored, so pass it on straight away. Five open invites at a time.",
			{},
			(_, { call }) => call("/v1/invites", { method: "POST", body: {} }),
		),

		tool(
			"my_invites",
			"Invites I have out, who has joined on them, and when they expire.",
			{},
			(_, { call }) => call("/v1/me/invites"),
		),

		tool(
			"set_lend_limit",
			say(
				"How many books I am willing to have out on loan at once. While I am at the limit my books stay listed but cannot be requested. Omit the number to lift the limit.",
				"How many things I am willing to have out on loan at once. While I am at the limit my things stay listed but cannot be requested. Omit the number to lift the limit.",
			),
			// The number is named for what is lent; either way it is the lend limit.
			{
				[noun === "book" ? "books" : "things"]: z
					.number()
					.int()
					.positive()
					.max(999)
					.optional(),
			} as { books: z.ZodOptional<z.ZodNumber> },
			(input, { call }) => {
				const limit = Object.values(
					input as Record<string, number | undefined>,
				)[0];
				return call("/v1/me", {
					method: "PATCH",
					body: { lendLimit: limit ?? null },
				});
			},
		),

		tool(
			"get_work",
			kind.isbn
				? "A book page: editions and every copy nearby with its owner and whether I can request it."
				: "A thing's page: who has it, their details about it, how many of a set are free, and whether I can ask for it.",
			{ workId: z.string() },
			({ workId }, { call }) => call(`/v1/works/${encodeURIComponent(workId)}`),
		),

		...(kind.isbn
			? [
					tool(
						"lookup_isbn",
						"What the catalogue knows about an ISBN-13, before listing it.",
						{ isbn13: z.string() },
						({ isbn13 }, { call }) =>
							call(`/v1/lookup/${encodeURIComponent(isbn13)}`),
					),
				]
			: []),

		tool("list_my_shelf", `The ${noun}s I have listed.`, {}, (_, { call }) =>
			call("/v1/me/shelf"),
		),

		kind.isbn
			? tool(
					"add_copy",
					"List a book I own. Give an ISBN-13, or a title and authors for books without one. Optional condition, lending policy, relay permission, note.",
					{
						isbn13: z.string().optional(),
						title: z.string().optional(),
						authors: z.array(z.string()).optional(),
						condition: z.enum(["new", "good", "worn", "fragile"]).optional(),
						lending: z.enum(["lendable", "reference", "paused"]).optional(),
						relayAllowed: z.boolean().optional(),
						note: z.string().max(280).optional(),
						/** For books without an ISBN record: an image URL the library will fetch and store. */
						coverImageUrl: z.string().url().optional(),
						/** Or the image itself: base64 (or a data: URL), JPEG/PNG/WebP, up to 2 MB. */
						coverImageBase64: z.string().min(16).optional(),
						coverImageType: z
							.enum(["image/jpeg", "image/png", "image/webp"])
							.optional(),
					},
					async (
						{
							isbn13,
							title,
							authors,
							coverImageUrl,
							coverImageBase64,
							coverImageType,
							...rest
						},
						{ call, upload },
					) => {
						let coverUrl: string | undefined;
						if (coverImageBase64) {
							const stored = await upload(coverImageBase64, coverImageType);
							if (stored.status !== 201 || !stored.body.coverUrl)
								return failed(stored);
							coverUrl = stored.body.coverUrl;
						} else if (coverImageUrl) {
							const stored = await call<{ coverUrl: string }>(
								"/v1/covers/from-url",
								{ method: "POST", body: { url: coverImageUrl } },
							);
							if (stored.status !== 201) return failed(stored);
							coverUrl = stored.body.coverUrl;
						}
						const created = await call<{ id: string }>("/v1/copies", {
							method: "POST",
							body: {
								...(isbn13 ? { isbn13 } : {}),
								...(title && authors?.length
									? {
											manual: {
												title,
												authors,
												...(coverUrl ? { coverUrl } : {}),
											},
										}
									: {}),
								...rest,
							},
						});
						if (created.status !== 201) return failed(created);
						// An ISBN book that resolved without a cover can still take the given image.
						if (coverUrl && isbn13) {
							await call(`/v1/copies/${encodeURIComponent(created.body.id)}`, {
								method: "PATCH",
								body: { coverUrl },
							});
						}
						return created;
					},
				)
			: tool(
					"add_copy",
					"List a thing I own and am happy to lend: what it is, how many (a set of 12 chairs is one item with quantity 12, borrowed in part), its category (see list_tags), and my own details about it. Each thing is its own entry. Optional condition, lending policy, note and a photo.",
					{
						name: z.string().min(1).max(120),
						quantity: z.number().int().min(1).max(500).optional(),
						category: z.string().optional(),
						brand: z.string().max(80).optional(),
						model: z.string().max(80).optional(),
						included: z.string().max(300).optional(),
						needs: z.string().max(300).optional(),
						care: z.string().max(300).optional(),
						/** The product's page on another website, for its manual and specifications. */
						link: z.string().url().max(500).optional(),
						condition: z.enum(["new", "good", "worn", "fragile"]).optional(),
						lending: z.enum(["lendable", "reference", "paused"]).optional(),
						note: z.string().max(280).optional(),
						photoImageUrl: z.string().url().optional(),
						photoImageBase64: z.string().min(16).optional(),
						photoImageType: z
							.enum(["image/jpeg", "image/png", "image/webp"])
							.optional(),
					},
					async (
						{
							name,
							quantity,
							category,
							brand,
							model,
							included,
							needs,
							care,
							link,
							photoImageUrl,
							photoImageBase64,
							photoImageType,
							...rest
						},
						{ call, upload },
					) => {
						let photoUrl: string | undefined;
						if (photoImageBase64) {
							const stored = await upload(photoImageBase64, photoImageType);
							if (stored.status !== 201 || !stored.body.coverUrl)
								return failed(stored);
							photoUrl = stored.body.coverUrl;
						} else if (photoImageUrl) {
							const stored = await call<{ coverUrl: string }>(
								"/v1/covers/from-url",
								{ method: "POST", body: { url: photoImageUrl } },
							);
							if (stored.status !== 201) return failed(stored);
							photoUrl = stored.body.coverUrl;
						}
						const details = Object.fromEntries(
							Object.entries({
								brand,
								model,
								included,
								needs,
								care,
								link,
							}).filter(([, value]) => value),
						);
						return call("/v1/copies", {
							method: "POST",
							body: {
								thing: {
									name,
									...(quantity ? { quantity } : {}),
									...(category ? { category } : {}),
									...(Object.keys(details).length ? { details } : {}),
									...(photoUrl ? { photoUrl } : {}),
								},
								...rest,
							},
						});
					},
				),

		tool(
			"set_cover",
			say(
				"Give one of my copies a cover from an image URL (JPEG, PNG or WebP, up to 2 MB). The library fetches and stores the image itself; the URL is not kept.",
				"Give one of my things a photo from an image URL (JPEG, PNG or WebP, up to 2 MB). The library fetches and stores the image itself; the URL is not kept.",
			),
			{ copyId: z.string(), imageUrl: z.string().url() },
			async ({ copyId, imageUrl }, { call }) => {
				const stored = await call<{ coverUrl: string }>("/v1/covers/from-url", {
					method: "POST",
					body: { url: imageUrl },
				});
				if (stored.status !== 201) return failed(stored);
				return call(`/v1/copies/${encodeURIComponent(copyId)}`, {
					method: "PATCH",
					body: { coverUrl: stored.body.coverUrl },
				});
			},
		),

		tool(
			"upload_cover",
			say(
				"Give one of my copies a cover from image bytes I already have: base64 (or a data: URL), JPEG/PNG/WebP, up to 2 MB. Use set_cover instead when the image is at a public URL.",
				"Give one of my things a photo from image bytes I already have: base64 (or a data: URL), JPEG/PNG/WebP, up to 2 MB. Use set_cover instead when the image is at a public URL.",
			),
			{
				copyId: z.string(),
				imageBase64: z.string().min(16),
				contentType: z
					.enum(["image/jpeg", "image/png", "image/webp"])
					.optional(),
			},
			async ({ copyId, imageBase64, contentType }, { call, upload }) => {
				const stored = await upload(imageBase64, contentType);
				if (stored.status !== 201 || !stored.body.coverUrl)
					return failed(stored);
				return call(`/v1/copies/${encodeURIComponent(copyId)}`, {
					method: "PATCH",
					body: { coverUrl: stored.body.coverUrl },
				});
			},
		),

		tool(
			"update_copy",
			kind.details
				? "Change one of my things: condition, lending (lendable / paused / reference), relay, loan days, note, how many there are (not while it is out), and my details about it (brand, model, included, needs, care), which replace the old ones."
				: "Change one of my copies: condition, lending (lendable / paused / reference), relay, loan days, note.",
			{
				copyId: z.string(),
				...(kind.details
					? {
							/** A new name for the thing. */
							name: z.string().min(1).max(120).optional(),
							quantity: z.number().int().min(1).max(500).optional(),
							details: z
								.object({
									brand: z.string().max(80).optional(),
									model: z.string().max(80).optional(),
									included: z.string().max(300).optional(),
									needs: z.string().max(300).optional(),
									care: z.string().max(300).optional(),
									link: z.string().url().max(500).optional(),
								})
								.nullable()
								.optional(),
						}
					: {}),
				condition: z.enum(["new", "good", "worn", "fragile"]).optional(),
				lending: z.enum(["lendable", "reference", "paused"]).optional(),
				relayAllowed: z.boolean().optional(),
				loanDays: z.number().int().positive().max(90).nullable().optional(),
				note: z.string().max(280).nullable().optional(),
			},
			({ copyId, ...input }, { call }) => {
				// A thing's name is its title in core.
				const { name, ...body } = input as typeof input & { name?: string };
				return call(`/v1/copies/${encodeURIComponent(copyId)}`, {
					method: "PATCH",
					body: { ...body, ...(name ? { title: name } : {}) },
				});
			},
		),

		tool(
			"list_my_loans",
			"Loans I am borrowing and lending, open ones and the last month of closed ones.",
			{},
			(_, { call }) => call("/v1/me/loans"),
		),

		tool(
			"request_loan",
			kind.sets
				? "Ask to borrow a thing (from get_work or search_catalogue). For a set (quantity above 1), say how many of it, up to those free. Optional note to the owner. The owner hears of it five minutes later; cancel_loan before then and they never do."
				: "Ask to borrow a copy (from get_work or search_catalogue). Works on a copy that is on loan too when the owner allows relays: the current reader then hands it straight to you. Optional note to the owner. The owner hears of it five minutes later; cancel_loan before then and they never do.",
			{
				copyId: z.string(),
				message: z.string().max(280).optional(),
				quantity: z.number().int().min(1).max(500).optional(),
			},
			({ copyId, message, quantity }, { call }) =>
				call("/v1/loans", {
					method: "POST",
					body: {
						copyId,
						...(message ? { message } : {}),
						...(quantity && quantity > 1 ? { quantity } : {}),
					},
				}),
		),

		tool(
			"respond_to_request",
			say(
				"As the owner, accept or decline a request on one of my books.",
				"As the owner, accept or decline a request on one of my things. For a set, the request says how many.",
			),
			{
				loanId: z.string(),
				decision: z.enum(["accept", "decline"]),
			},
			({ loanId, decision }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/${decision}`, {
					method: "POST",
				}),
		),

		tool(
			"cancel_loan",
			"Cancel a request or an accepted loan before the handoff. Within five minutes of asking, the owner never hears of the request.",
			{ loanId: z.string() },
			({ loanId }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/cancel`, {
					method: "POST",
				}),
		),

		tool(
			"join_waitlist",
			say(
				"Follow a book (a work id) I cannot request right now; I get 48 hours of first dibs when a copy frees up.",
				"Follow a thing (a work id) I cannot request right now; I get 48 hours of first dibs when one frees up.",
			),
			{ workId: z.string() },
			({ workId }, { call }) =>
				call("/v1/waitlist", { method: "POST", body: { workId } }),
		),

		tool(
			"my_waitlist",
			say(
				"Books I am waiting for, my position in each queue, and any copy currently held for me.",
				"Things I am waiting for, my position in each queue, and any one currently held for me.",
			),
			{},
			(_, { call }) => call("/v1/me/waitlist"),
		),

		tool(
			"leave_waitlist",
			say(
				"Stop waiting for a book (waitlist entry id from my_waitlist).",
				"Stop waiting for a thing (waitlist entry id from my_waitlist).",
			),
			{ entryId: z.string() },
			({ entryId }, { call }) =>
				call(`/v1/waitlist/${encodeURIComponent(entryId)}`, {
					method: "DELETE",
				}),
		),

		tool(
			"extend_loan",
			say(
				"Push a loan's due date back (default 7 days, twice per loan). Borrowers can only extend when nobody is waiting for the book; owners always can.",
				"Push a loan's due date back (default 7 days, twice per loan). Borrowers can only extend when nobody is waiting for it; owners always can.",
			),
			{
				loanId: z.string(),
				days: z.number().int().min(1).max(21).optional(),
			},
			({ loanId, days }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/extend`, {
					method: "POST",
					body: days ? { days } : {},
				}),
		),

		tool(
			"report_problem",
			say(
				"Report a problem with a loan to the community moderators: damage, loss, no_show, conduct or other. A loss report closes the loan and takes the copy off the shelves.",
				"Report a problem with a loan to the community moderators: damage, loss, no_show, conduct or other. A loss report closes the loan; a whole thing comes off the list, and lost parts of a set come off its count.",
			),
			{
				loanId: z.string(),
				kind: z.enum(["damage", "loss", "no_show", "conduct", "other"]),
				body: z.string().max(1000).optional(),
			},
			({ loanId, kind, body }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/report`, {
					method: "POST",
					body: { kind, ...(body ? { body } : {}) },
				}),
		),

		tool(
			"nudge",
			"Send the other party a gentle reminder about a loan (once a day).",
			{ loanId: z.string() },
			({ loanId }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/nudge`, {
					method: "POST",
				}),
		),

		tool(
			"get_loan_messages",
			"The conversation on a loan.",
			{ loanId: z.string() },
			({ loanId }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/messages`),
		),

		tool(
			"post_loan_message",
			"Say something on a loan's thread.",
			{ loanId: z.string(), body: z.string().min(1).max(1000) },
			({ loanId, body }, { call }) =>
				call(`/v1/loans/${encodeURIComponent(loanId)}/messages`, {
					method: "POST",
					body: { body },
				}),
		),
	];
}
